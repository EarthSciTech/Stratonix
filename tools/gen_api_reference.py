#!/usr/bin/env python3
"""Generate docs/api_reference.md from the comments in the public headers (Doxygen fallback).

Collects, for every header under include/ and capi/include/, the file comment and each
documented declaration: a block of '///' or '/** */' comments followed by the declaration line(s)
up to ';' or '{'. Usage: gen_api_reference.py <source root> <output.md>
"""
import re, sys, pathlib

def doc_blocks(text):
    lines = text.splitlines()
    i, out = 0, []
    while i < len(lines):
        l = lines[i].strip()
        if l.startswith("///") or l.startswith("/**"):
            doc = []
            if l.startswith("/**"):
                while True:
                    s = lines[i].strip()
                    doc.append(re.sub(r"^/\*\*|\*/$|^\*", "", s).strip())
                    if s.endswith("*/"): break
                    i += 1
            else:
                while i < len(lines) and lines[i].strip().startswith("///"):
                    doc.append(lines[i].strip()[3:].strip().lstrip("<").strip()); i += 1
                i -= 1
            i += 1
            decl = []
            while i < len(lines) and len(decl) < 6:
                s = lines[i].rstrip()
                if not s.strip() or s.strip().startswith("//"): break
                decl.append(s.strip())
                if s.rstrip().endswith((";", "{", "}")) or s.strip().startswith("#define"): break
                i += 1
            d = " ".join(decl).rstrip("{").strip()
            if d.startswith(("#pragma", "#include", "#ifndef")): d = "(file)"
            text_doc = " ".join(x for x in doc if x and not x.startswith("@file")).replace("@brief", "").strip()
            if d and text_doc: out.append((d, text_doc))
        i += 1
    return out

def main(root, outp):
    root = pathlib.Path(root)
    heads = sorted(root.glob("include/stratonix/**/*.hpp")) + sorted(root.glob("include/stratonix/**/*.h")) + sorted(root.glob("capi/include/*.h"))
    md = ["# Stratonix API reference", "",
          "Generated by `tools/gen_api_reference.py` from the header comments (the same comments Doxygen reads with `docs/Doxyfile`).",
          "Namespaces: `stratonix` (C++ library), C functions prefixed `stx_` (stable C API).", ""]
    for h in heads:
        blocks = doc_blocks(h.read_text())
        if not blocks: continue
        md += [f"## {h.relative_to(root).as_posix()}", ""]
        for d, t in blocks:
            md += [f"- `{d}`  ", f"  {t}"]
        md.append("")
    pathlib.Path(outp).write_text("\n".join(md) + "\n")
    print(f"wrote {outp}: {len(heads)} headers")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
